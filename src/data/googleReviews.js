export function verifiedFiveStarReviews(collection) {
  if (!collection.profile.verified || !collection.profile.url) return [];
  const ids = new Set();
  const excludedAuthors = new Set((collection.selection?.excludedAuthors || []).map((name) => name.trim().toLocaleLowerCase('en-US')));
  return collection.reviews.filter((review) => {
    const valid = review.verified === true && review.rating === 5 &&
      typeof review.id === 'string' && review.id.length > 0 && !ids.has(review.id) &&
      typeof review.author === 'string' && review.author.trim().length > 0 &&
      !excludedAuthors.has(review.author.trim().toLocaleLowerCase('en-US')) &&
      typeof review.text === 'string' && review.text.trim().length > 0 && review.source === 'Google Maps' &&
      typeof review.retrievedAt === 'string' && review.retrievedAt.length > 0;
    if (valid) ids.add(review.id);
    return valid;
  });
}
